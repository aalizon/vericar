export function findDemoCase(rawQuery) {
  const normalized = String(rawQuery || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
  if (!normalized) return null;
  return (
    DEMO_CASES.find((c) =>
      c.identifiers.some((id) => id.toUpperCase().replace(/[^A-Z0-9]/g, '') === normalized)
    ) || null
  );
}
